#!/usr/bin/env python3
# plan variants for --plan-from, built from plans/claude-opus-5-5 (rules in plans/VARIANTS.md)
# usage: python3 scripts/plan_variants.py build    writes plans/<variant>/<kernel>/<level>.txt from the sources below
#        python3 scripts/plan_variants.py check    leaks, code in plans, seeded errors detectable, word counts
# sources: plans/algo_only/PLANS.txt and plans/lowlevel_only/PLANS.txt ("=== kernel" or "=== kernel.L2" blocks,
#          a block without level is used for every level that has no own block), plans/cheatsheet/CHEATSHEET.txt,
#          plans/seeded_error/seeds.json (plan and ref.c replacements per kernel)

import json
import os
import re
import subprocess
import sys
import tempfile

from gen_desc import DESC, ROOT, load_kernel, plan_has_code, run
from md import heading, table

PLANS = os.path.join(ROOT, "plans")
TEACHER = os.path.join(PLANS, "claude-opus-5-5")
LEVELS = ["L0", "L1", "L2", "L3"]
VARIANTS = ["algo_only", "lowlevel_only", "cheatsheet", "seeded_error"]
KERNELS = sorted(k for k in os.listdir(TEACHER) if os.path.isdir(os.path.join(TEACHER, k)))

REGISTER = r"%?\b(?:r[abcd]x|r[sd]i|r[sb]p|r(?:8|9|1[0-5])[dwb]?|e[abcd]x|[xyz]mm\d+)\b"
MNEMONIC = (r"\b(?:v?mov(?:[qlwb]|abs\w*|[su]d|[au]p[sd]|dq[au]|[sz]x\w*|msk\w*|mskpd)?|lea[ql]?|push[ql]?|pop[ql]?|ret[ql]?|cmov\w+|cmp[ql]?|imul[ql]?|sh[lr][ql]?|sar[ql]?|"
            r"xor\w*|vzeroupper|vbroadcast\w*|vextract\w*|v\w+p[ds]|v\w+s[ds]|popcnt|movabs\w*|j(?:mp|n?[lgeabz]e?))\b")
ISA = (r"System V|callee|caller|\bstack\b|\bABI\b|\bpush|\bpop\b|\bAVX|\bSSE|SIMD|\bFMA\b|\bVEX\b|\d+-bit (?:register|vector)|"
       r"256-bit|128-bit|\blanes?\b|broadcast|vector (?:part|loop|load|store)|scalar (?:part|loop|tail)|\btails?\b|"
       r"align|\.rodata|immediate|conditional move|\bflags\b|\bbytes?\b|\bregisters?\b|encod|instruction")
LOOP = (r"\bfor each\b|\bfor [a-z]{1,2} from\b|\bwhile [a-z]\w* *[<>]|\bloops?\b|iterat|row by row|in this order|"
        r"half-step|\bswap|binary search|compare-exchange|insertion|sum over|dot product|average|\+=|"
        r"\b[A-Za-z_]\w*\[[^\]]+\](?:\[[^\]]+\])? *= *[^=]|\bphase\b|\bstep \d")
LEAKS = {"algo_only": [("register", REGISTER), ("mnemonic", MNEMONIC), ("ISA/ABI", ISA)],
         "lowlevel_only": [("algorithm", LOOP)]}


def path(variant, kernel, level, ext=".txt"):
    return os.path.join(PLANS, variant, kernel, level + ext)


def read(p):
    return open(p).read().strip()


def write(p, text):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w") as f:
        f.write(text.rstrip() + "\n")


def blocks(source):
    out = {}
    for block in re.split(r"^=== ", open(source).read(), flags=re.M)[1:]:
        name, _, body = block.partition("\n")
        out[name.strip()] = body.strip()
    return out


def replace_all(text, pairs, where):
    for old, new in pairs:
        if old not in text:
            sys.exit(f"{where}: not found: {old[:70]!r}")
        text = text.replace(old, new)
    return text


def build_seeded():
    seeds = json.load(open(os.path.join(PLANS, "seeded_error", "seeds.json")))
    doc = ["# Seeded errors", "",
           "One algorithmic error per kernel, the same at every level. Plans are the teacher plans with the replacements",
           "below; `<kernel>/seeded_ref.c` is `kernels/desc/<kernel>/ref.c` with the same error, used to check that the",
           "tests detect it and to classify answers that reproduce it. Generated by `scripts/plan_variants.py build`.", ""]
    for kernel in KERNELS:
        s = seeds[kernel]
        for level in LEVELS:
            teacher = read(path("claude-opus-5-5", kernel, level))
            text = teacher
            for old, new in s["plan"]:
                text = text.replace(old, new)
            if text == teacher:
                sys.exit(f"seeded_error {kernel} {level}: no replacement applied")
            write(path("seeded_error", kernel, level), text)
        unused = [old for old, _ in s["plan"] if not any(old in read(path("claude-opus-5-5", kernel, l)) for l in LEVELS)]
        if unused:
            sys.exit(f"seeded_error {kernel}: replacement never applies: {unused[0][:70]!r}")
        ref = replace_all(open(os.path.join(DESC, kernel, "ref.c")).read(), s["ref"], f"{kernel}/ref.c")
        write(os.path.join(PLANS, "seeded_error", kernel, "seeded_ref.c"), ref)
        doc += [f"## {kernel}", "", f"Error: {s['error']}.", "", "Plan changes:", ""]
        doc += [f"- `{old.strip()}`\n  → `{new.strip()}`" for old, new in s["plan"]] + [""]
    write(os.path.join(PLANS, "seeded_error", "ERRORS.md"), "\n".join(doc))


def build():
    for variant in ("algo_only", "lowlevel_only"):
        src = blocks(os.path.join(PLANS, variant, "PLANS.txt"))
        unknown = {n.split(".")[0] for n in src} - set(KERNELS)
        if unknown:
            sys.exit(f"{variant}: unknown kernels {unknown}")
        for kernel in KERNELS:
            for level in LEVELS:
                text = src.get(f"{kernel}.{level}") or src.get(kernel)
                if text is None:
                    sys.exit(f"{variant}: no block for {kernel} {level}")
                write(path(variant, kernel, level), text)
    sheet = read(os.path.join(PLANS, "cheatsheet", "CHEATSHEET.txt"))
    for kernel in KERNELS:
        for level in LEVELS:
            write(path("cheatsheet", kernel, level), sheet)
    build_seeded()
    print(f"built {len(VARIANTS)} variants x {len(KERNELS)} kernels x {len(LEVELS)} levels")


def leaks(variant, text):
    hits = []
    for kind, pattern in LEAKS.get(variant, []):
        for line in text.splitlines():
            found = sorted({m.group(0) for m in re.finditer(pattern, line, re.I if kind != "register" else 0)})
            if found:
                hits.append((kind, ", ".join(found), line.strip()))
    return hits


def seeded_detected(kernel, work):
    _, spec, _ = load_kernel(kernel, "L0")
    kdir = os.path.join(DESC, kernel)
    ref = re.search(r"\b(ref_\w+)\s*\(", open(os.path.join(kdir, "ref.c")).read()).group(1)
    exe = os.path.join(work, kernel)
    for cmd in (["gcc", "-O2", "-c", "-D", f"{ref}={spec['name']}", os.path.join(PLANS, "seeded_error", kernel, "seeded_ref.c"),
                 "-o", exe + ".o"],
                ["gcc", "-O2", "-I", os.path.join(DESC, "common"), os.path.join(kdir, "driver.c"),
                 os.path.join(kdir, "ref.c"), exe + ".o", "-o", exe, "-lm"]):
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            return "build failed: " + r.stderr.strip().splitlines()[-1]
    stage, sizes = run(exe)[:2]
    return f"{stage} (sizes passed: {sum(v == 'pass' for v in sizes.values())}/{len(sizes)})"


def check():
    ok = True
    heading("Leaks (each line is a match to review)")
    rows = []
    for variant in VARIANTS:
        for kernel in KERNELS:
            seen = set()
            for level in LEVELS:
                p = path(variant, kernel, level)
                if not os.path.exists(p):
                    rows.append([variant, kernel, level, "missing", "", ""])
                    ok = False
                    continue
                text = read(p)
                if text in seen:
                    continue
                seen.add(text)
                if plan_has_code(text):
                    rows.append([variant, kernel, level, "has code", "", ""])
                for kind, found, line in leaks(variant, text):
                    rows.append([variant, kernel, level, kind, f"`{found}`", line.replace("|", "\\|")])
    table(["variant", "kernel", "level", "kind", "match", "line"], rows)
    print(f"{len(rows)} matches\n")

    heading("Seeded errors: the tests must fail on seeded_ref.c")
    work = tempfile.mkdtemp(prefix="plan_variants_")
    rows = []
    for kernel in KERNELS:
        changed = sum(read(path("seeded_error", kernel, l)) != read(path("claude-opus-5-5", kernel, l)) for l in LEVELS)
        result = seeded_detected(kernel, work)
        ok &= changed == len(LEVELS) and result.startswith(("wrong", "crash", "timeout"))
        rows.append([kernel, f"{changed}/{len(LEVELS)}", result])
    table(["kernel", "levels changed", "tests on seeded_ref.c"], rows)

    heading("Words per plan (mean over levels)")
    names = ["claude-opus-5-5"] + VARIANTS
    words = {v: {k: [len(read(path(v, k, l)).split()) for l in LEVELS] for k in KERNELS} for v in names}
    mean = lambda xs: sum(xs) / len(xs)
    rows = [[k] + [f"{mean(words[v][k]):.0f}" for v in names] for k in KERNELS]
    rows.append(["**mean**"] + [f"**{mean([w for k in KERNELS for w in words[v][k]]):.0f}**" for v in names])
    rows.append(["ratio to teacher"] + [f"{mean([w for k in KERNELS for w in words[v][k]]) / mean([w for k in KERNELS for w in words[names[0]][k]]):.2f}"
                                        for v in names])
    table(["kernel"] + names, rows)
    print("all variants present, seeded errors detected" if ok else "problems found")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    {"build": build, "check": check}[sys.argv[1]]()
